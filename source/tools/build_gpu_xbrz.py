#!/usr/bin/env python3
"""Compile the derived xBRZ1.9 kernels and validate their Vulkan1.0 SPIR-V."""
from pathlib import Path
import argparse,hashlib,json,struct,subprocess,tempfile

def main():
 p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True);a=p.parse_args()
 shaders=Path(__file__).resolve().parents[1]/'external_reader/shaders'
 names=[('PreprocessShader','vulkan_xbrz_preprocess.comp'),('ScaleShader','vulkan_xbrz_scale.comp')]
 lines=['#pragma once','#include <cstdint>','// Generated by tools/build_gpu_xbrz.py; derived GPL xBRZ1.9 kernels.','namespace external { namespace gpuxbrz {']
 report={'common_sha256':hashlib.sha256((shaders/'vulkan_xbrz_common.glsl').read_bytes()).hexdigest(),'kernels':{}}
 with tempfile.TemporaryDirectory(prefix='ra2-gpu-xbrz-') as tmp:
  for symbol,filename in names:
   source=shaders/filename;binary=Path(tmp)/(filename+'.spv')
   subprocess.run(['glslangValidator','-V','--target-env','vulkan1.0','-Os','-I'+str(shaders),'-o',str(binary),str(source)],check=True)
   subprocess.run(['spirv-val','--target-env','vulkan1.0',str(binary)],check=True)
   assembly=subprocess.check_output(['spirv-dis',str(binary)],text=True)
   assert 'OpCapability Float64' in assembly, 'xBRZ shader lost required float64 arithmetic'
   no_contraction=assembly.count('NoContraction')
   assert no_contraction>0, 'xBRZ shader lost precise/NoContraction decorations'
   data=binary.read_bytes();words=struct.unpack('<'+'I'*(len(data)//4),data);assert words[0]==0x07230203
   lines.append('inline constexpr uint32_t '+symbol+'[]={')
   for n in range(0,len(words),8):lines.append(' '+','.join('0x%08xu'%w for w in words[n:n+8])+',')
   lines.append('};')
   report['kernels'][filename]={'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'spirv_sha256':hashlib.sha256(data).hexdigest(),'bytes':len(data),'words':len(words),'float64':True,'no_contraction_decorations':no_contraction}
 lines+=['}}',''];a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text('\n'.join(lines),encoding='utf-8');print(json.dumps(report))

if __name__=='__main__':main()
